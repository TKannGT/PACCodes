function run_sims!(SNR, N,L,F,depths,TMat,trials; seed = seed)
    TotalParams = "===================Evaluating ["*string(N)*","*string(length(A))*","*"L="*string(L)*"]==================="
    println(TotalParams)
    println("Information Set A: $A")
    noises = length(SNR)
    total_error = zeros(noises)
    elapsed_time = @elapsed begin
        prev_bad = nothing 
        for i in 1:noises
                σ = fσ(SNR[i],N,K) 
                println("Channel: AWGN Channel with SNR = "*string(SNR[i]))
                result, new_prev_bad = decode_sim(σ,N,L,F,depths,TMat,trials;T=Float64, seed = seed, prev_bad = prev_bad, fast = false, l_fast = 32)
                total_error[i] = result
                prev_bad = new_prev_bad
                println("FER = "*string(result))
        end 
    end
    println(total_error)
    println("Elapsed time: $elapsed_time seconds")
    return total_error 
end 


